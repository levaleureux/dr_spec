module DrSpec
  module Coverage
    class HtmlReporter
      include HtmlHelpers

      def initialize(tracker)
        @tracker = tracker
      end

      def write(path = "coverage/index.html")
        $gtk.write_file(path, generate)
        puts "📊 Coverage HTML written to #{path}"
      end

      def generate
        files = build_file_data
        total_covered, total_executable = @tracker.total_stats
        total_pct = pct(total_covered, total_executable)

        html_page(files, total_covered, total_executable, total_pct)
      end

      private

      def build_file_data
        @tracker.tracked_files.map do |file|
          covered, executable = @tracker.file_stats(file)
          next if executable == 0

          build_file_hash(file, covered, executable)
        end.compact
      end

      def build_file_hash(file, covered, executable)
        {
          path: file, covered: covered, executable: executable,
          pct: pct(covered, executable),
          uncovered: @tracker.uncovered_lines(file),
          hits: @tracker.hit_data[file] || {},
          sources: @tracker.sources[file] || []
        }
      end

      def html_page(files, total_covered, total_exec, total_pct)
        [
          html_head, "<body>",
          html_header(total_covered, total_exec, total_pct),
          "<main>", html_summary_table(files), html_file_details(files), "</main>",
          html_footer, "</body></html>"
        ].join("\n")
      end

      def html_head
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n" \
          "<meta charset=\"utf-8\">\n" \
          "<title>dr_spec Coverage Report</title>\n" \
          "<style>\n#{HtmlStyle.css}\n</style>\n</head>"
      end

      def html_header(covered, executable, total_pct)
        color = color_for_pct(total_pct)
        "<header><h1>dr_spec Coverage Report</h1>" \
          "<div class=\"total\">" \
          "<span class=\"badge\" style=\"background:#{color}\">#{total_pct}%</span>" \
          "<span class=\"stats\">#{covered}/#{executable} lines covered</span>" \
          "</div></header>"
      end

      def html_summary_table(files)
        rows = files.map { |f| summary_row(f) }.join("\n")
        "<h2>Files</h2><table><thead><tr>" \
          "<th>File</th><th>Coverage</th><th>Lines</th>" \
          "</tr></thead><tbody>#{rows}</tbody></table>"
      end

      def summary_row(file)
        color = color_for_pct(file[:pct])
        anchor = file[:path].gsub("/", "_")
        "<tr><td><a href=\"##{anchor}\">#{file[:path]}</a></td><td>" \
          "<div class=\"bar-bg\">" \
          "<div class=\"bar\" style=\"width:#{file[:pct]}%;background:#{color}\"></div></div>" \
          "<span class=\"pct\" style=\"color:#{color}\">#{file[:pct]}%</span>" \
          "</td><td>#{file[:covered]}/#{file[:executable]}</td></tr>"
      end

      def html_file_details(files)
        files.map { |f| file_detail(f) }.join("\n")
      end

      def file_detail(file)
        anchor = file[:path].gsub("/", "_")
        color = color_for_pct(file[:pct])
        lines = file[:sources].each_with_index.map do |line, idx|
          source_line(line, idx + 1, file[:hits])
        end.join("\n")

        "<div class=\"file-detail\" id=\"#{anchor}\">" \
          "<h3>#{file[:path]} <span class=\"badge-sm\" style=\"background:#{color}\">#{file[:pct]}%</span></h3>" \
          "<pre class=\"source\">#{lines}</pre></div>"
      end

      def html_footer
        "<footer>Generated by <strong>dr_spec</strong> Coverage &mdash; #{Time.now}</footer>"
      end
    end
  end
end
